#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include <string.h>

extern "C" void smhasher_blake3_rust(const void *, size_t, void *);

static bool check(const void *data, size_t len, const uint8_t expected[32])
{
  uint8_t result[32];
  smhasher_blake3_rust(data, len, result);
  if (memcmp(result, expected, 32) == 0) return true;
  fprintf(stderr, "Rust BLAKE3 vector failed for %zu bytes\n", len);
  return false;
}

int main()
{
  static const uint8_t empty[32] = {
    0xaf,0x13,0x49,0xb9,0xf5,0xf9,0xa1,0xa6,0xa0,0x40,0x4d,0xea,0x36,0xdc,0xc9,0x49,
    0x9b,0xcb,0x25,0xc9,0xad,0xc1,0x12,0xb7,0xcc,0x9a,0x93,0xca,0xe4,0x1f,0x32,0x62
  };
  static const uint8_t short_input[32] = {
    0xe1,0xbe,0x4d,0x7a,0x8a,0xb5,0x56,0x0a,0xa4,0x19,0x9e,0xea,0x33,0x98,0x49,0xba,
    0x8e,0x29,0x3d,0x55,0xca,0x0a,0x81,0x00,0x67,0x26,0xd1,0x84,0x51,0x9e,0x64,0x7f
  };
  static const uint8_t chunk[32] = {
    0x42,0x21,0x47,0x39,0xf0,0x95,0xa4,0x06,0xf3,0xfc,0x83,0xde,0xb8,0x89,0x74,0x4a,
    0xc0,0x0d,0xf8,0x31,0xc1,0x0d,0xaa,0x55,0x18,0x9b,0x5d,0x12,0x1c,0x85,0x5a,0xf7
  };
  static const uint8_t over_chunk[32] = {
    0xd0,0x02,0x78,0xae,0x47,0xeb,0x27,0xb3,0x4f,0xae,0xcf,0x67,0xb4,0xfe,0x26,0x3f,
    0x82,0xd5,0x41,0x29,0x16,0xc1,0xff,0xd9,0x7c,0x8c,0xb7,0xfb,0x81,0x4b,0x84,0x44
  };
  uint8_t data[1025];
  for (size_t i = 0; i < sizeof(data); ++i) data[i] = i % 251;
  return !(check(NULL, 0, empty) && check(data, 3, short_input) &&
           check(data, 1024, chunk) && check(data, 1025, over_chunk));
}
