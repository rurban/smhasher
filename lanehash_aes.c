/* lane path: AES-NI, one lane per xmm (L = 4, 8, 16 via a generating macro)  */

#define LH_C128(i) _mm_loadu_si128((const __m128i *)LH_C[i])

static inline __m128i lh_finish128(__m128i acc, uint64_t len) {
    __m128i ln = _mm_set1_epi64x((long long)len);
    acc = _mm_aesenc_si128(acc, _mm_xor_si128(LH_C128(24), ln));
    acc = _mm_aesenc_si128(acc, LH_C128(25));
    return _mm_aesenc_si128(acc, LH_C128(26));
}

#define LH_DEFINE_XMM(NAME, L, ABSORB)                                                        \
static inline __m128i NAME(const uint8_t *p, size_t len, uint64_t seed) {                \
    __m128i t[L], sd = _mm_set1_epi64x((long long)seed), ln = _mm_set1_epi64x((long long)len); \
    size_t n = (len + 15) / 16, m = n - (L), full = m / (L), rem = m % (L), j;           \
    const uint8_t *c = p + len - 16 * (L);                                              \
    __m128i acc;                                                                        \
    unsigned i;                                                                         \
    LH_UNROLL for (i = 0; i < (L); i++)                                                           \
        t[i] = _mm_xor_si128(sd, LH_C128(i));                                           \
    for (j = 0; j < full; j++, p += 16 * (L))                                           \
        LH_UNROLL for (i = 0; i < (L); i++)                                             \
            ABSORB(t[i], p + 16 * i);                                                   \
    LH_UNROLL for (i = 0; i < rem; i++)                                                 \
        ABSORB(t[i], p + 16 * i);                                                                                   \
    LH_UNROLL for (i = 0; i < (L); i++) {                                                         \
        __m128i e = _mm_xor_si128(_mm_loadu_si128((const __m128i *)(c + 16 * i)), ln);  \
        LH_REG(e);                                                                      \
        t[i] = _mm_aesenc_si128(_mm_xor_si128(t[i], e), e);                             \
    }                                                                                   \
    LH_UNROLL for (i = 0; i < (L); i++) {                                                         \
        t[i] = _mm_aesenc_si128(t[i], LH_C128(40));                                     \
        t[i] = _mm_aesenc_si128(t[i], LH_C128(41));                                     \
        t[i] = _mm_aesenc_si128(t[i], LH_C128(42));                                     \
    }                                                                                   \
    acc = t[0];                                                                         \
    for (i = 1; i < (L); i++)                                                           \
        acc = _mm_add_epi64(acc, t[i]);                                                 \
    return lh_finish128(acc, (uint64_t)len);                                            \
}

