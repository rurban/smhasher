/* Keep a loaded block in a register: gcc otherwise folds the load into the memory
 * operands of both the XOR and the AES instruction and loads every block twice. */
#if defined(__GNUC__)
#  define LH_REG(v) __asm__("" : "+x"(v))
#else
#  define LH_REG(v) ((void)0)
#endif
/* Absorb one 16-byte block at q into lane t: t = AES(t ^ b) ^ b, the block pinned
 * in a register (see LH_REG). */
#define LH_ABSORB_REG(t, q) do {                                                        \
        __m128i b_ = _mm_loadu_si128((const __m128i *)(q));                             \
        LH_REG(b_);                                                                     \
        (t) = _mm_aesenc_si128(_mm_xor_si128((t), b_), b_);                             \
    } while (0)

#if defined(__GNUC__)
#  define LH_NOINLINE __attribute__((noinline))
#  define LH_INLINE static inline __attribute__((always_inline))
#elif defined(_MSC_VER)
#  define LH_NOINLINE __declspec(noinline)
#  define LH_INLINE static __forceinline
#else
#  define LH_NOINLINE
#  define LH_INLINE static inline
#endif

/* Lane loops must be fully unrolled so the lane state stays in registers. */
#if defined(__clang__)
#  define LH_UNROLL _Pragma("clang loop unroll(full)")
#elif defined(__GNUC__) && __GNUC__ >= 8
#  define LH_UNROLL _Pragma("GCC unroll 16")
#else
#  define LH_UNROLL
#endif

