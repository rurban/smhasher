/* lanehash_aes - C port of the Rust definition (lanehash/src/aes/{spec,lanes,short}.rs).
 *
 *   len <= 64: two to five protected 64x64->128 multiplies over the input words with
 *              per-seed secrets, then one unprotected fold per output half.
 *   len >  64: L = 4 (len <= 256) / 8 (len <= 1024) / 16 lanes; 16-byte block j enters
 *              lane j mod L as data and round key, t = AES(t ^ b) ^ b; the last 16*L
 *              bytes, XORed with the broadcast length, close each lane the same way;
 *              three constant-key rounds per lane; lanes added; three finaliser rounds,
 *              the first keyed with the length.
 *
 * Backends, chosen at compile time, all bit-identical:
 *   LANEHASH_AES_PORTABLE, or no AES intrinsics: T-table software AES
 *              (lanehash_aes_ttables.h, generated by gen_ttables.py).
 *   __AES__ (-maes, MSVC /arch:AVX2+): one lane per xmm register.
 *   __VAES__ && __AVX2__: two lanes per ymm register.
 *
 * SPDX-License-Identifier: MIT OR Apache-2.0
 */
#include "lanehash_aes.h"
